import React, { useState, useEffect } from 'react';
import {
  Sparkles,
  BookOpen,
  CheckCircle2,
  AlertCircle,
  Copy,
  Download,
  Share2,
  RefreshCw,
  Lightbulb,
  Crosshair,
  Cpu,
  TrendingUp,
  ShieldAlert,
  ArrowRight
} from 'lucide-react';
import { ResearchPaper, StructuredPaperSummary } from '../types/index.ts';
import { apiClient } from '../services/apiClient.ts';

interface AiSummaryViewProps {
  initialPaper?: ResearchPaper | null;
  corpusPapers?: ResearchPaper[];
}

export const AiSummaryView: React.FC<AiSummaryViewProps> = ({
  initialPaper,
  corpusPapers = []
}) => {
  const [selectedPaperId, setSelectedPaperId] = useState<string>(initialPaper?.id || '');
  const [title, setTitle] = useState(initialPaper?.title || '');
  const [abstract, setAbstract] = useState(initialPaper?.abstract || '');
  const [loading, setLoading] = useState(false);
  const [summary, setSummary] = useState<StructuredPaperSummary | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);

  useEffect(() => {
    if (initialPaper) {
      setSelectedPaperId(initialPaper.id);
      setTitle(initialPaper.title);
      setAbstract(initialPaper.abstract);
    }
  }, [initialPaper]);

  const handleSelectCorpusPaper = (paperId: string) => {
    setSelectedPaperId(paperId);
    const found = corpusPapers.find(p => p.id === paperId);
    if (found) {
      setTitle(found.title);
      setAbstract(found.abstract);
      setSummary(null);
    }
  };

  const handleGenerateSummary = async () => {
    if (!abstract.trim()) {
      setError('Please provide an abstract to summarize.');
      return;
    }

    setLoading(true);
    setError(null);
    try {
      const res = await apiClient.summarizePaper(title || 'Academic Paper', abstract);
      setSummary(res);
    } catch (err: any) {
      setError(err.message || 'Summarization failed.');
    } finally {
      setLoading(false);
    }
  };

  const handleCopy = () => {
    if (!summary) return;
    const text = `# Structured Research Summary: ${title}

## Executive Summary
${summary.conciseSummary}

## Research Problem
${summary.researchProblem}

## Main Objective
${summary.mainObjective}

## Methodology
${summary.methodology}

## Key Findings
${summary.keyFindings}

## Limitations
${summary.limitations}

## Future Directions
${summary.futureDirections.map(d => `- ${d}`).join('\n')}

## Suggested Keywords
${summary.suggestedKeywords.join(', ')}
`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handleDownloadMarkdown = () => {
    if (!summary) return;
    const content = `# Structured Research Summary: ${title}
Generated By: ${summary.generatedBy === 'gemini' ? 'Gemini 3.8 Flash' : 'Scientific Heuristic NLP Engine'}
Timestamp: ${summary.generatedAt}

### 1. Executive Summary
${summary.conciseSummary}

### 2. Fundamental Research Problem
${summary.researchProblem}

### 3. Primary Objective & Hypothesis
${summary.mainObjective}

### 4. Technical Methodology
${summary.methodology}

### 5. Empirical Findings
${summary.keyFindings}

### 6. Acknowledged Limitations
${summary.limitations}

### 7. Strategic Future Directions
${summary.futureDirections.map(d => `- ${d}`).join('\n')}

### 8. Domain Keywords
${summary.suggestedKeywords.join(', ')}
`;
    const blob = new Blob([content], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `summary_${title.slice(0, 30).replace(/[^a-z0-9]/gi, '_')}.md`;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="p-6 space-y-6 max-w-6xl mx-auto">
      {/* Header Banner */}
      <div className="p-6 rounded-2xl bg-[#0A1020] border border-cyan-500/20 shadow-xl space-y-3">
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
          <div>
            <span className="text-[11px] font-bold uppercase tracking-wider text-cyan-400 flex items-center gap-1.5">
              <Sparkles className="w-4 h-4 text-violet-400" />
              <span>AI Research Assistant &amp; Discourse Parser</span>
            </span>
            <h2 className="text-xl font-bold text-white tracking-tight mt-0.5">
              Structured Paper Summarizer
            </h2>
          </div>
        </div>

        <p className="text-xs text-slate-400 leading-relaxed max-w-3xl">
          Deconstructs complex academic abstracts into 8 rigorous scientific components: problem statement, objective, methodology, empirical findings, limitations, future trajectories, and keywords. Uses server-side Gemini 3.8 Flash when configured, with an algorithmic discourse parser fallback.
        </p>
      </div>

      {/* Input Selection Card */}
      <div className="p-6 rounded-2xl bg-[#0A1020] border border-slate-800 space-y-4 shadow-xl text-xs">
        {corpusPapers.length > 0 && (
          <div>
            <label className="text-slate-300 font-semibold mb-1 block">
              Quick Select from Active Corpus:
            </label>
            <select
              value={selectedPaperId}
              onChange={e => handleSelectCorpusPaper(e.target.value)}
              className="w-full px-3 py-2 rounded-lg bg-slate-900 border border-slate-800 text-cyan-300 focus:outline-none focus:border-cyan-500 text-xs"
            >
              <option value="">-- Choose an indexed paper or type custom abstract below --</option>
              {corpusPapers.map(p => (
                <option key={p.id} value={p.id}>
                  [{p.category}] {p.title} ({p.publication_year})
                </option>
              ))}
            </select>
          </div>
        )}

        <div>
          <label className="text-slate-300 font-semibold mb-1 block">Paper Title:</label>
          <input
            type="text"
            value={title}
            onChange={e => setTitle(e.target.value)}
            placeholder="e.g., Adaptive Graph Neural Networks for Zero-Day Malware Detection"
            className="w-full px-3 py-2.5 rounded-lg bg-slate-900 border border-slate-800 text-white focus:outline-none focus:border-cyan-500 font-medium"
          />
        </div>

        <div>
          <label className="text-slate-300 font-semibold mb-1 block">Research Abstract Text:</label>
          <textarea
            rows={5}
            value={abstract}
            onChange={e => setAbstract(e.target.value)}
            placeholder="Paste complete abstract body here..."
            className="w-full px-3 py-2.5 rounded-lg bg-slate-900 border border-slate-800 text-white focus:outline-none focus:border-cyan-500 leading-relaxed"
          />
        </div>

        {error && (
          <div className="p-3 rounded-lg bg-red-500/10 border border-red-500/20 text-red-300 flex items-center gap-2">
            <AlertCircle className="w-4 h-4 shrink-0 text-red-400" />
            <span>{error}</span>
          </div>
        )}

        <button
          onClick={handleGenerateSummary}
          disabled={loading || !abstract.trim()}
          className="w-full sm:w-auto px-6 py-2.5 rounded-xl bg-gradient-to-r from-violet-600 to-cyan-600 hover:from-violet-500 hover:to-cyan-500 text-white font-semibold text-xs transition-all shadow-lg shadow-violet-500/20 flex items-center justify-center gap-2 cursor-pointer disabled:opacity-50"
        >
          {loading ? (
            <RefreshCw className="w-4 h-4 animate-spin" />
          ) : (
            <Sparkles className="w-4 h-4" />
          )}
          <span>{loading ? 'Deconstructing Abstract...' : 'Generate Structured Summary'}</span>
        </button>
      </div>

      {/* Structured Summary Output */}
      {summary && (
        <div className="p-6 rounded-2xl bg-[#0A1020] border border-cyan-500/30 space-y-5 shadow-2xl animate-in fade-in duration-200">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-4 border-b border-slate-800">
            <div>
              <div className="flex items-center gap-2">
                <span className="text-[10px] font-bold uppercase tracking-wider text-cyan-400">
                  Structured Research Breakdown
                </span>
                <span
                  className={`text-[10px] font-mono px-2 py-0.5 rounded ${
                    summary.generatedBy === 'gemini'
                      ? 'bg-violet-500/20 text-violet-300 border border-violet-500/30'
                      : 'bg-cyan-500/10 text-cyan-300 border border-cyan-500/30'
                  }`}
                >
                  {summary.generatedBy === 'gemini' ? 'Gemini 3.8 Flash' : 'Scientific Heuristic NLP Engine'}
                </span>
              </div>
              <h3 className="text-base font-bold text-white tracking-tight mt-1">
                {title || 'Academic Paper Analysis'}
              </h3>
            </div>

            <div className="flex items-center gap-2">
              <button
                onClick={handleCopy}
                className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white border border-slate-700 text-xs font-medium transition-colors cursor-pointer"
              >
                {copied ? <CheckCircle2 className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{copied ? 'Copied' : 'Copy'}</span>
              </button>

              <button
                onClick={handleDownloadMarkdown}
                className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-slate-800 hover:bg-slate-700 text-slate-300 hover:text-white border border-slate-700 text-xs font-medium transition-colors cursor-pointer"
              >
                <Download className="w-3.5 h-3.5" />
                <span>Export Markdown</span>
              </button>
            </div>
          </div>

          {/* 1. Concise Executive Summary */}
          <div className="p-4 rounded-xl bg-slate-900/80 border border-slate-800 text-xs leading-relaxed space-y-1">
            <span className="text-cyan-400 font-bold uppercase tracking-wider text-[10px] block">
              1. Executive Summary
            </span>
            <p className="text-slate-200 font-medium">{summary.conciseSummary}</p>
          </div>

          {/* Grid of Core Pillars */}
          <div className="grid grid-cols-1 md:grid-cols-2 gap-4 text-xs">
            {/* Research Problem */}
            <div className="p-4 rounded-xl bg-slate-900/60 border border-slate-800 space-y-1.5">
              <div className="flex items-center gap-1.5 text-red-400 font-bold text-[11px]">
                <ShieldAlert className="w-4 h-4 shrink-0" />
                <span>Fundamental Research Problem</span>
              </div>
              <p className="text-slate-300 text-[11px] leading-relaxed">
                {summary.researchProblem}
              </p>
            </div>

            {/* Main Objective */}
            <div className="p-4 rounded-xl bg-slate-900/60 border border-slate-800 space-y-1.5">
              <div className="flex items-center gap-1.5 text-cyan-400 font-bold text-[11px]">
                <Crosshair className="w-4 h-4 shrink-0" />
                <span>Primary Objective &amp; Hypothesis</span>
              </div>
              <p className="text-slate-300 text-[11px] leading-relaxed">
                {summary.mainObjective}
              </p>
            </div>

            {/* Technical Methodology */}
            <div className="p-4 rounded-xl bg-slate-900/60 border border-slate-800 space-y-1.5">
              <div className="flex items-center gap-1.5 text-indigo-400 font-bold text-[11px]">
                <Cpu className="w-4 h-4 shrink-0" />
                <span>Computational Methodology &amp; Pipeline</span>
              </div>
              <p className="text-slate-300 text-[11px] leading-relaxed">
                {summary.methodology}
              </p>
            </div>

            {/* Empirical Findings */}
            <div className="p-4 rounded-xl bg-slate-900/60 border border-slate-800 space-y-1.5">
              <div className="flex items-center gap-1.5 text-emerald-400 font-bold text-[11px]">
                <TrendingUp className="w-4 h-4 shrink-0" />
                <span>Empirical Findings &amp; Benchmark Gains</span>
              </div>
              <p className="text-slate-300 text-[11px] leading-relaxed">
                {summary.keyFindings}
              </p>
            </div>
          </div>

          {/* Limitations */}
          <div className="p-4 rounded-xl bg-slate-900/60 border border-slate-800 text-xs space-y-1">
            <span className="text-amber-400 font-bold text-[11px] block">
              Acknowledged Constraints &amp; Trade-offs
            </span>
            <p className="text-slate-300 text-[11px] leading-relaxed">{summary.limitations}</p>
          </div>

          {/* Strategic Future Directions */}
          {summary.futureDirections && summary.futureDirections.length > 0 && (
            <div className="p-4 rounded-xl bg-slate-900/60 border border-slate-800 text-xs space-y-2">
              <span className="text-violet-400 font-bold text-[11px] flex items-center gap-1.5">
                <Lightbulb className="w-4 h-4" />
                <span>Recommended Future Research Trajectories</span>
              </span>
              <ul className="space-y-1 text-slate-300 text-[11px]">
                {summary.futureDirections.map((dir, i) => (
                  <li key={i} className="flex items-start gap-2">
                    <span className="text-cyan-400 font-mono text-[10px]">[{i + 1}]</span>
                    <span>{dir}</span>
                  </li>
                ))}
              </ul>
            </div>
          )}

          {/* Suggested Keywords */}
          {summary.suggestedKeywords && summary.suggestedKeywords.length > 0 && (
            <div className="flex flex-wrap items-center gap-1.5 pt-2 border-t border-slate-800/80">
              <span className="text-slate-500 font-medium text-[11px] mr-1">Extracted Keywords:</span>
              {summary.suggestedKeywords.map(kw => (
                <span
                  key={kw}
                  className="px-2 py-0.5 rounded bg-slate-900 text-cyan-300 border border-slate-800 text-[10px] font-mono"
                >
                  #{kw}
                </span>
              ))}
            </div>
          )}
        </div>
      )}
    </div>
  );
};
